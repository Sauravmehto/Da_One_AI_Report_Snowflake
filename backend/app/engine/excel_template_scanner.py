"""Excel template scanner — classify an uploaded .xlsx so a report can later be
regenerated from it safely.

This module is deliberately PURE: it takes a workbook (or a path) and returns a
plain-dict description. It never touches Snowflake, the filesystem beyond the one
file it is asked to read, or any other project module — so it is trivially
unit-testable and cannot affect the existing query/safety paths.

Nothing in this module is specific to any particular template, sheet, column, or
cell name. Detection is purely structural (formula shape + reference offsets).

Jobs:

1. Sheet roles — "formula" / "parameter" / "data" from the formula-vs-value mix.

2. Formula tiers:
     - Tier 1  (auto-regenerate): an aggregate (SUM/SUMIF/SUMIFS/COUNTIF/
       COUNTIFS/AVERAGEIF/SUMPRODUCT) over a multi-cell RANGE. Re-extend the
       range to a new row count.
     - Tier 1b (auto-regenerate, NEW): a "row-mirror block" — a contiguous
       vertical run of cells in one column where each cell's formula is the cell
       above it with every relative row reference shifted by exactly +1 (Excel
       fill-down). This is how a template lays one output row per data row. It is
       regenerated by extending/shrinking the block to the new row count,
       reproducing the shifted-reference pattern. Detected structurally, so a
       block is ONE unit — never one Tier-2 flag per cell per row.
     - Tier 2  (one-time human review): anything not provably safe — a single
       fixed cross-sheet cell reference, a lookup, an unrecognized function, or a
       vertical run whose per-row offset is NOT a clean +1 (a fragile hand-wired
       reference). Flagged, never auto-rewritten.
     - Tier 3  (static): self-contained cells with no ranges and no cross-sheet
       references. Left exactly as-is.

3. Fingerprint — sha256 over (sheet names + header rows + every formula's pattern
   with row numbers normalized away). Invariant to data-row count, so the same
   template shape matches a previously approved fingerprint.
"""

from __future__ import annotations

import hashlib
import re
from collections import defaultdict
from datetime import date, datetime, time
from typing import Any

import openpyxl
from openpyxl.utils import column_index_from_string, get_column_letter

try:  # array/table formulas come back as wrapper objects, not plain strings
    from openpyxl.worksheet.formula import ArrayFormula, DataTableFormula
    _FORMULA_WRAPPERS: tuple[type, ...] = (ArrayFormula, DataTableFormula)
except Exception:  # pragma: no cover - very old openpyxl
    _FORMULA_WRAPPERS = ()

# --- classification thresholds (heuristic; documented so they can be tuned) ---
FORMULA_SHEET_RATIO = 0.15   # >= this share of populated cells are formulas -> "formula"
MIN_MIRROR_ROWS = 3          # a row-mirror block must be at least this many rows
# A "data" tab = a header row followed by a contiguous block of >= this many
# record rows whose columns are type-consistent going DOWN. A "parameter" tab
# (scattered label/value pairs, section headers, blank rows, a type-mixed value
# column — a fund-parameters/config sheet) fails one of these and is not "data".
MIN_DATA_TABLE_ROWS = 3
DATA_COL_CONSISTENCY = 0.75  # fraction of header columns that must be type-consistent

# Aggregate functions considered safe to auto-regenerate over a range (Tier 1).
SAFE_AGG_FUNCTIONS = frozenset(
    {"SUM", "SUMIF", "SUMIFS", "COUNTIF", "COUNTIFS", "AVERAGEIF", "SUMPRODUCT"}
)

_FUNC_RE = re.compile(r"([A-Z][A-Z0-9.]*)\s*\(")
# A1:B2, $A$1:$B$2, or whole-column A:A / row 1:1 ranges.
_RANGE_RE = re.compile(r"\$?[A-Za-z]{1,3}\$?\d*:\$?[A-Za-z]{1,3}\$?\d*")
# A sheet-qualified reference: Sheet1! or 'My Sheet'! before a cell/range.
_CROSS_SHEET_RE = re.compile(r"(?:'[^']+'|[A-Za-z_][A-Za-z0-9_.]*)!")
# A sheet-qualified SINGLE cell (Sheet1!B5) — used to spot formulas pinned to one record.
_CROSS_SHEET_CELL_RE = re.compile(
    r"(?:'[^']+'|[A-Za-z_][A-Za-z0-9_.]*)!\$?[A-Za-z]{1,3}\$?\d+"
)
_DIGITS_RE = re.compile(r"\d+")

# One A1-style cell reference (optionally sheet-qualified, optionally $-absolute),
# anchored so it is a whole token and NOT a function name like LOG10( .
_CELL_REF_RE = re.compile(
    r"(?<![A-Za-z0-9_$])"
    r"(?P<sheet>(?:'[^']+'|[A-Za-z_][A-Za-z0-9_.]*)!)?"
    r"(?P<colabs>\$?)(?P<col>[A-Za-z]{1,3})(?P<rowabs>\$?)(?P<row>\d+)"
    r"(?![A-Za-z0-9_(])"
)


def shift_formula_rows(formula: str, delta: int) -> str:
    """Return `formula` with every RELATIVE row number in every A1-style cell
    reference shifted by `delta` (Excel fill-down). Absolute rows ($3) and every
    non-reference number (thresholds, multipliers) are left unchanged."""
    def _repl(m: re.Match) -> str:
        if m.group("rowabs") == "$":            # absolute row: never shifts
            return m.group(0)
        new_row = int(m.group("row")) + delta
        if new_row < 1:                          # can't shift above row 1
            return m.group(0)
        return f"{m.group('sheet') or ''}{m.group('colabs')}{m.group('col')}" \
               f"{m.group('rowabs')}{new_row}"

    return _CELL_REF_RE.sub(_repl, formula)


def _shape(formula: str) -> str:
    """The formula's structural shape, with row numbers (and any literal digits)
    normalized away: `=D!K3` and `=D!K4` share a shape; `=SUM(E6:E10)` does not."""
    return _DIGITS_RE.sub("#", formula)


def fixed_record_refs(formula: str) -> list[str]:
    """Sheet-qualified SINGLE-cell references in a formula (ranges removed first).

    This is the risk signal that actually matters to a human reviewer: a formula
    holding one of these is pinned to ONE specific record. If the data's row count
    or order changes, it silently reads a DIFFERENT record — no error, just a wrong
    number. Aggregates over ranges (which we re-extend) don't have this problem."""
    body = formula[1:] if formula.startswith("=") else formula
    return _CROSS_SHEET_CELL_RE.findall(_RANGE_RE.sub("", body))


def _formula_text(cell) -> str | None:
    """Return the formula text for a cell, or None if it isn't a formula."""
    value = cell.value
    if _FORMULA_WRAPPERS and isinstance(value, _FORMULA_WRAPPERS):
        text = getattr(value, "text", None) or getattr(value, "ref", None) or ""
        return str(text)
    if cell.data_type == "f" and isinstance(value, str):
        return value
    if isinstance(value, str) and value.startswith("="):
        return value
    return None


def classify_formula(formula: str) -> tuple[str, str, dict[str, Any]]:
    """Sort ONE formula (in isolation) into a tier. Returns (tier, reason, meta).

    Note this never returns tier_1b — row-mirror is a property of a *run* of
    cells, decided by detect_row_mirror_blocks, not of a single formula."""
    body = formula[1:] if formula.startswith("=") else formula
    upper = body.upper()
    funcs = set(_FUNC_RE.findall(upper))
    ranges = _RANGE_RE.findall(body)
    has_range = bool(ranges)
    has_cross_sheet = bool(_CROSS_SHEET_RE.search(body))
    unsafe_funcs = funcs - SAFE_AGG_FUNCTIONS

    if funcs and not unsafe_funcs and has_range:
        agg = ",".join(sorted(funcs))
        return (
            "tier_1",
            f"aggregate ({agg}) over a range — safe to regenerate against a new row count",
            {"ranges": ranges, "functions": sorted(funcs)},
        )
    if unsafe_funcs:
        return (
            "tier_2",
            "uses non-aggregate/unrecognized function(s): " + ",".join(sorted(unsafe_funcs)),
            {},
        )
    if has_cross_sheet and not has_range:
        return ("tier_2", "single fixed cross-sheet cell reference — verify once by hand", {})
    if has_range:
        return ("tier_2", "bare range reference without a recognized aggregate", {})
    return ("tier_3", "self-contained/static — never regenerated", {})


def detect_row_mirror_blocks(cells: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Find Tier-1b row-mirror blocks among one sheet's formula cells.

    A block is a maximal run of cells in the SAME column that are BOTH row-contiguous
    AND share a formula SHAPE (row numbers normalized away), in which every adjacent
    pair is a clean +1 fill-down, and where the shift actually changes something (so
    a run of identical constants isn't mistaken for a mirror).

    Segmenting by shape is what makes this correct on real templates. A block is
    routinely bounded by a DIFFERENT kind of formula — e.g. a totals row
    `=SUM(E6:E10)` sitting directly under the mirror `=Data!K3..K7`. That totals row
    is a natural BOUNDARY, not a violation: it has a different shape, so it simply
    ends the segment and classifies on its own.

    Within one shape, however, a jumbled offset IS the signature of hand-wiring
    (e.g. refs going ...L6, L7, L3, L4, L5) — such a segment is rejected outright
    rather than being split into a "clean" sub-block, and its cells fall back to
    per-cell classification (typically Tier 2).

    Purely structural: no sheet/column/cell name is referenced."""
    by_col: dict[str, dict[int, dict[str, Any]]] = defaultdict(dict)
    for fc in cells:
        by_col[fc["col"]][fc["row"]] = fc

    blocks: list[dict[str, Any]] = []
    for col, rowmap in by_col.items():
        rows = sorted(rowmap)
        if not rows:
            continue

        # maximal segments that are contiguous in row AND identical in shape
        segments: list[list[int]] = []
        current = [rows[0]]
        for prev, row in zip(rows, rows[1:]):
            same_shape = (_shape(rowmap[row]["formula"]) == _shape(rowmap[prev]["formula"]))
            if row == prev + 1 and same_shape:
                current.append(row)
            else:
                segments.append(current)
                current = [row]
        segments.append(current)

        for seg in segments:
            if len(seg) < MIN_MIRROR_ROWS:
                continue
            template = rowmap[seg[0]]["formula"]
            if shift_formula_rows(template, 1) == template:  # nothing shifts
                continue
            consistent = all(
                shift_formula_rows(rowmap[seg[k]]["formula"], 1)
                == rowmap[seg[k + 1]]["formula"]
                for k in range(len(seg) - 1)
            )
            if not consistent:      # same shape, jumbled offsets -> hand-wired
                continue
            blocks.append({
                "sheet": rowmap[seg[0]]["sheet"],
                "column": col,
                "start_row": seg[0],
                "end_row": seg[-1],
                "rows": len(seg),
                "template_formula": template,
                "cells": [rowmap[r]["coord"] for r in seg],
            })
    return blocks


def header_row_index(ws) -> int:
    """Index of the first row with >= 2 populated cells (skips a single-cell title
    banner), else the first populated row, else 1."""
    first_populated = None
    for row in ws.iter_rows():
        non_empty = [c for c in row if c.value is not None and str(c.value).strip() != ""]
        if non_empty:
            if first_populated is None:
                first_populated = non_empty[0].row
            if len(non_empty) >= 2:
                return non_empty[0].row
    return first_populated or 1


def header_labels(ws, header_row: int) -> dict[str, str]:
    """{column_letter: header label} for a given header row (blank cells omitted)."""
    out: dict[str, str] = {}
    for cell in ws[header_row]:
        if cell.value is not None and str(cell.value).strip() != "":
            out[cell.column_letter] = str(cell.value)
    return out


def _normalized_cell_type(value) -> str | None:
    """Coarse type of a cell value for column-consistency checks: None (empty),
    'formula', 'num' (int/float/bool), 'date', or 'str'. int vs float are the same
    'num' — real data columns freely mix them."""
    if value is None or (isinstance(value, str) and value.strip() == ""):
        return None
    if isinstance(value, str) and value.startswith("="):
        return "formula"
    if isinstance(value, bool):
        return "num"
    if isinstance(value, (int, float)):
        return "num"
    if isinstance(value, (datetime, date, time)):
        return "date"
    return "str"


def _looks_like_data_table(ws, header_row: int) -> bool:
    """A structural data-vs-parameter test (independent of cell count).

    True when the header row (>= 2 named columns) is followed by a CONTIGUOUS run
    of >= MIN_DATA_TABLE_ROWS record rows — each filling a majority of the header
    columns — AND the columns are type-consistent going DOWN (>= DATA_COL_CONSISTENCY
    of them). A scattered label/value parameter sheet (blank rows / section headers
    break the run; its value column mixes types) fails and is classified 'parameter'."""
    header_cols = [c.column_letter for c in ws[header_row]
                   if c.value is not None and str(c.value).strip() != ""]
    width = len(header_cols)
    if width < 2:
        return False
    col_idxs = [column_index_from_string(c) for c in header_cols]
    need = max(2, (width + 1) // 2)          # a record row fills a majority of cols

    record_rows: list[int] = []
    r = header_row + 1
    while r <= ws.max_row:
        present = sum(1 for ci in col_idxs
                      if _normalized_cell_type(ws.cell(row=r, column=ci).value) is not None)
        if present < need:                    # blank row / section header ends the run
            break
        record_rows.append(r)
        r += 1
    if len(record_rows) < MIN_DATA_TABLE_ROWS:
        return False

    consistent = 0
    for ci in col_idxs:
        types = {t for rr in record_rows
                 if (t := _normalized_cell_type(ws.cell(row=rr, column=ci).value)) is not None}
        if len(types) <= 1:
            consistent += 1
    return (consistent / width) >= DATA_COL_CONSISTENCY


def _scan_sheet(ws) -> dict[str, Any]:
    """Per-sheet stats, role, header, and raw formula cells."""
    formula_cells: list[dict[str, Any]] = []
    value_count = 0
    for row in ws.iter_rows():
        for cell in row:
            ftext = _formula_text(cell)
            if ftext is not None:
                formula_cells.append({
                    "sheet": ws.title, "coord": cell.coordinate,
                    "col": cell.column_letter, "row": cell.row, "formula": ftext,
                })
            elif cell.value is not None and str(cell.value).strip() != "":
                value_count += 1

    formula_count = len(formula_cells)
    populated = formula_count + value_count
    ratio = (formula_count / populated) if populated else 0.0

    hdr_idx = header_row_index(ws)
    header_by_col: dict[str, str] = {}
    header: list[str] = []
    for cell in ws[hdr_idx]:
        label = "" if cell.value is None else str(cell.value)
        header.append(label)
        if label.strip():
            header_by_col[cell.column_letter] = label

    # A formula-heavy sheet is "formula"; otherwise distinguish a real record
    # table ("data") from scattered config ("parameter") STRUCTURALLY — not by
    # cell count, which cannot tell a small data table from a parameter sheet.
    if formula_count and ratio >= FORMULA_SHEET_RATIO:
        role = "formula"
    elif _looks_like_data_table(ws, hdr_idx):
        role = "data"
    else:
        role = "parameter"

    return {
        "name": ws.title, "role": role, "formula_cells": formula_cells,
        "formula_count": formula_count, "value_count": value_count,
        "formula_ratio": round(ratio, 4), "header_row": hdr_idx,
        "header": header, "header_by_col": header_by_col,
    }


def _fingerprint(sheets: list[dict[str, Any]]) -> str:
    """Stable hash of the template's SHAPE — invariant to row count. Includes ALL
    formula cells (row-normalized), so a mirror block of any length collapses to a
    single pattern."""
    parts: list[str] = []
    for sheet in sheets:
        parts.append("SHEET:" + sheet["name"])
        parts.append("HDR:" + "|".join(sheet["header"]))
        patterns = {
            _DIGITS_RE.sub("#", fc["coord"]) + "=" + _DIGITS_RE.sub("#", fc["formula"])
            for fc in sheet["formula_cells"]
        }
        parts.extend("F:" + p for p in sorted(patterns))
    return hashlib.sha256("\n".join(parts).encode("utf-8")).hexdigest()


def scan_workbook(wb, template_name: str) -> dict[str, Any]:
    """Classify an already-open workbook. Pure — no I/O."""
    sheets = [_scan_sheet(ws) for ws in wb.worksheets]

    tab_roles = {s["name"]: s["role"] for s in sheets}
    header_by_col = {s["name"]: s["header_by_col"] for s in sheets}
    header_rows = {s["name"]: s["header_row"] for s in sheets}
    tiers: dict[str, list[dict[str, Any]]] = {
        "tier_1": [], "tier_1b": [], "tier_2": [], "tier_3": []
    }

    for s in sheets:
        blocks = detect_row_mirror_blocks(s["formula_cells"])
        claimed = {coord for b in blocks for coord in b["cells"]}
        tiers["tier_1b"].extend(blocks)
        for fc in s["formula_cells"]:
            if fc["coord"] in claimed:
                continue
            tier, reason, meta = classify_formula(fc["formula"])
            entry = {"sheet": fc["sheet"], "cell": fc["coord"], "formula": fc["formula"],
                     "reason": reason}
            if tier == "tier_1":
                entry["ranges"] = meta["ranges"]
                entry["functions"] = meta["functions"]
            if tier == "tier_2":
                # Split the catch-all bucket by ACTUAL risk, so a reviewer sees the
                # few formulas that can silently go wrong — not every unrecognized one.
                pinned = fixed_record_refs(fc["formula"])
                entry["risk"] = "high" if pinned else "low"
                if pinned:
                    entry["fixed_refs"] = pinned
                    entry["reason"] = (
                        "pinned to specific record(s) " + ", ".join(pinned) +
                        " — if the data's row count or order changes this silently "
                        "reads a DIFFERENT record. NEEDS HUMAN REVIEW."
                    )
                else:
                    entry["reason"] = reason + " — not auto-regenerated, but nothing "
                    entry["reason"] += "in it depends on the row count (informational)"
            tiers[tier].append(entry)

    return {
        "template_name": template_name,
        "fingerprint": _fingerprint(sheets),
        "tab_roles": tab_roles,
        "header_by_col": header_by_col,
        "header_rows": header_rows,
        "formula_classification": tiers,
        "summary": {
            "sheets": len(sheets),
            "tier_1": len(tiers["tier_1"]),
            "tier_1b_blocks": len(tiers["tier_1b"]),
            "tier_1b_cells": sum(b["rows"] for b in tiers["tier_1b"]),
            "tier_2": len(tiers["tier_2"]),
            # the only number a human actually has to act on:
            "tier_2_needs_review": sum(1 for c in tiers["tier_2"] if c.get("risk") == "high"),
            "tier_3": len(tiers["tier_3"]),
        },
        "sheets": [
            {k: s[k] for k in ("name", "role", "formula_count", "value_count",
                               "formula_ratio", "header_row", "header")}
            for s in sheets
        ],
    }


def scan_file(path: str) -> dict[str, Any]:
    """Load an .xlsx from disk and classify it. Keeps formulas (data_only=False)."""
    import os

    wb = openpyxl.load_workbook(path, data_only=False)
    name = os.path.splitext(os.path.basename(path))[0]
    try:
        return scan_workbook(wb, name)
    finally:
        wb.close()


def scan_bytes(data: bytes, template_name: str) -> dict[str, Any]:
    """Classify an .xlsx given its raw bytes (e.g. a file uploaded in chat).
    Identical classification to scan_file — both open the workbook and delegate to
    scan_workbook; only the source (BytesIO vs path) differs."""
    import io

    wb = openpyxl.load_workbook(io.BytesIO(data), data_only=False)
    try:
        return scan_workbook(wb, template_name)
    finally:
        wb.close()
